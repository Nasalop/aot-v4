#!/usr/bin/env python3
"""Generate src/runtime/d3d10_proxy_gen.inc: per-method marshalling tables for the PE32-guest -> 64-bit DXVK COM proxy.
usage: gen_d3d10_proxy.py <dxvk>/include/native/directx > d3d10_proxy_gen.inc"""
import re, sys, os
d = sys.argv[1]
src = ''.join(open(os.path.join(d, f)).read() for f in ('dxgi.h', 'd3d10.h', 'd3d10_1.h'))
ifs = {}; order = []
for m in re.finditer(r'MIDL_INTERFACE\("([0-9a-fA-F-]+)"\)\s*\n(\w+)\s*:\s*public\s+(\w+)\s*\{(.*?)\n\};', src, re.S):
    g, name, base, body = m.groups()
    if not (name.startswith('ID3D10') or name.startswith('IDXGI')): continue
    meths = []
    for mm in re.finditer(r'virtual\s+([\w\s\*]+?)\s+STDMETHODCALLTYPE\s+(\w+)\((.*?)\)\s*=\s*0;', body, re.S):
        ret, mn, args = mm.groups()
        al = [a.strip() for a in args.replace('\n', ' ').split(',') if a.strip() and a.strip() != 'void']
        meths.append((ret.strip(), mn, al))
    ifs[name] = (g, base, meths); order.append(name)
IUNK = [('HRESULT', 'QueryInterface', ['REFIID riid', 'void **ppvObject']), ('ULONG', 'AddRef', []), ('ULONG', 'Release', [])]
def flat(n):
    if n == 'IUnknown': return list(IUNK)
    return flat(ifs[n][1]) + ifs[n][2]
ids = {n: i for i, n in enumerate(order)}
SPECIAL = {  # (method) -> {argindex: kind}; applied by interface family
 ('ID3D10Device', 'CreateBuffer'): {1: 'd'}, ('ID3D10Device', 'CreateTexture1D'): {1: 'd'}, ('ID3D10Device', 'CreateTexture2D'): {1: 'd'}, ('ID3D10Device', 'CreateTexture3D'): {1: 'd'},
 ('ID3D10Device', 'CreateInputLayout'): {0: 'e'}, ('ID3D10Device', 'CreateGeometryShaderWithStreamOutput'): {2: 's'},
 ('IDXGIFactory', 'CreateSwapChain'): {1: 'c'}, ('IDXGISwapChain', 'GetDesc'): {0: 'C'},
 ('IDXGIAdapter', 'GetDesc'): {0: 'a'}, ('IDXGIAdapter1', 'GetDesc1'): {0: 'b'}, ('IDXGIOutput', 'GetDesc'): {0: 'w'},
 ('ID3D10Buffer', 'Map'): {2: 'M'}, ('ID3D10Texture1D', 'Map'): {3: 'X'}, ('ID3D10Texture2D', 'Map'): {3: 'T'}, ('ID3D10Texture3D', 'Map'): {3: 'U'},
 ('IDXGISurface', 'Map'): {0: 'X'}, ('IDXGISurface', 'GetDC'): {0: 'X'}, ('IDXGISurface1', 'GetDC'): {0: 'X'},
}
def classify(iface, mn, al):
    ks = []; ci = []; ty = []; seen_num = None; used_arr = False
    for i, a in enumerate(al):
        a2 = re.sub(r'\bconst\b', '', a); nm = re.findall(r'(\w+)$', a.replace('[4]', ''))[0]
        k, c, t = 'u', 255, 255
        if re.search(r'\*\s*const\s*\*', a): k = 'A'; c = seen_num if seen_num is not None else 255
        elif '**' in a2.replace(' ', ''):
            tn = re.match(r'\s*(\w+)', a2).group(1)
            if tn == 'void': k = 'R'; c = i - 1
            else:
                k = 'O'; t = ids.get(tn, 254)
                if seen_num is not None and not used_arr and 'Get' in mn and nm.startswith('pp'): k = 'B'; c = seen_num; used_arr = True
        elif '*' in a2 or '[' in a: 
            tn = re.match(r'\s*(\w+)', a2).group(1)
            k = 'o' if (tn.startswith('ID3D10') or tn.startswith('IDXGI') or tn == 'IUnknown') else 'v'
        elif re.match(r'\s*(REFIID|REFGUID)\b', a2): k = 'v'
        elif re.match(r'\s*(float|FLOAT)\b', a2): k = 'f'
        elif re.match(r'\s*(UINT64|DOUBLE|LARGE_INTEGER|LONGLONG)\b', a2): k = 'X'
        if nm.startswith('Num') and k == 'u': seen_num = i
        ks.append(k); ci.append(c); ty.append(t)
    for (si, sm), ov in SPECIAL.items():
        if sm == mn and (si == iface or (si, iface) in (('ID3D10Device', 'ID3D10Device1'), ('IDXGIFactory', 'IDXGIFactory1'), ('IDXGIAdapter', 'IDXGIAdapter1'), ('IDXGISurface', 'IDXGISurface1'))) :
            for i, k in ov.items():
                ks[i] = k
                if k == 'e': ci[i] = i + 1
                if k == 's': ci[i] = i + 1
    return ks, ci, ty
out = ['/* generated by tools/gen_d3d10_proxy.py from the DXVK headers - do not edit */']
out.append('static const PI PIS[%d];' % len(order))
for n in order:
    g = ifs[n][0].replace('-', ''); gb = ', '.join('0x' + g[i:i+2] for i in range(0, 32, 2))
    # GUID wire layout: d1(le4) d2(le2) d3(le2) d4(8)
    b = bytes.fromhex(g); wire = b[0:4][::-1] + b[4:6][::-1] + b[6:8][::-1] + b[8:]
    ms = flat(n); rows = []
    for (ret, mn, al) in ms:
        ks, ci, ty = classify(n, mn, al)
        rows.append('  { "%s", %d, "%s", {%s}, {%s}, %d },' % (mn, len(al), ''.join(ks), ','.join(map(str, ci)) or '0', ','.join(map(str, ty)) or '0', 0 if ret == 'void' else 1))
    out.append('static const PM PM_%s[] = {\n%s\n};' % (n, '\n'.join(rows)))
    out.append('#define W_%s(S) static uint64_t W_%s_##S(CPU *c) { return px_call(c, &PIS[%d], S); }' % (n, n, ids[n]))
    out.append(''.join('W_%s(%d)' % (n, i) for i in range(len(ms))))
    out.append('static const fn_t WF_%s[] = { %s };' % (n, ', '.join('W_%s_%d' % (n, i) for i in range(len(ms)))))
    out.append('static const uint8_t GUID_%s[16] = { %s };' % (n, ', '.join('0x%02x' % x for x in wire)))
out.append('static const PI PIS[] = {\n' + '\n'.join('  { "%s", sizeof PM_%s / sizeof PM_%s[0], PM_%s, WF_%s, GUID_%s },' % ((n,) * 6) for n in order) + '\n};')
print('\n'.join(out))
